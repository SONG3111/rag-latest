-- 基线 schema：单机 SQLite（原 db/DbInitializer 的 DDL + 增量迁移）到 Postgres 的
-- 一次性重建。因为上线方式定为「空库 + 重新上传」，这里可以直接把约束加严：
--   * workspaces.owner_user_id 是 NOT NULL —— 多租户的租户键（Dify 的 tenant_id 同位）；
--   * chunks.workspace_id 补上此前缺失的外键；
--   * 时间列由 SQLite 时代的 epoch-ms 整数改为 timestamptz；
--   * JSON 载荷列沿用 text + Jackson（不走 jsonb：迁移期间保持序列化语义逐字节不变，
--     jsonb 记为后续可选项）。
-- 索引名沿用 SQLite 版（ix_*），便于对照旧库排障。

-- --------------------------------------------------------------------------
-- 身份：平台级账号。Dify 的 accounts / tenant_account_joins 把角色挂在
-- 「账号 ↔ 工作区」的关联表上；本项目当前是单层隔离（一个工作区一个 owner），
-- 因此 role 直接落在 users 上，工作区归属落在 workspaces.owner_user_id。
-- 共享工作区（成员表 + owner/editor/viewer）是下一轮的增量迁移。
-- --------------------------------------------------------------------------
CREATE TABLE users (
    id            VARCHAR(32)  NOT NULL PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    display_name  VARCHAR(100) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(16)  NOT NULL DEFAULT 'member',
    status        VARCHAR(16)  NOT NULL DEFAULT 'active',
    last_login_at TIMESTAMPTZ,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role   CHECK (role IN ('admin', 'member')),
    CONSTRAINT ck_users_status CHECK (status IN ('active', 'disabled'))
);

-- 邮箱大小写不敏感：登录与唯一性都按小写比较，避免 A@x.com / a@x.com 双开号。
CREATE UNIQUE INDEX uq_users_email_lower ON users (lower(email));

-- --------------------------------------------------------------------------
-- 业务表
-- --------------------------------------------------------------------------
CREATE TABLE workspaces (
    id            VARCHAR(32)  NOT NULL PRIMARY KEY,
    owner_user_id VARCHAR(32)  NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name          VARCHAR(200) NOT NULL,
    description   TEXT,
    created_at    TIMESTAMPTZ  NOT NULL,
    updated_at    TIMESTAMPTZ  NOT NULL
);

CREATE INDEX ix_workspaces_owner_user_id ON workspaces (owner_user_id);

CREATE TABLE document_files (
    id          VARCHAR(32) NOT NULL PRIMARY KEY,
    workspace_id VARCHAR(32) NOT NULL REFERENCES workspaces (id) ON DELETE CASCADE,
    rel_path    VARCHAR(500) NOT NULL,
    kind        VARCHAR(20)  NOT NULL,
    size_bytes  BIGINT       NOT NULL DEFAULT 0,
    checksum    VARCHAR(64)  NOT NULL DEFAULT '',
    status      VARCHAR(8)   NOT NULL DEFAULT 'pending',
    chunk_count INTEGER      NOT NULL DEFAULT 0,
    error       TEXT,
    indexed_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ  NOT NULL,
    CONSTRAINT uq_file_per_ws UNIQUE (workspace_id, rel_path)
);

CREATE INDEX ix_document_files_workspace_id ON document_files (workspace_id);

CREATE TABLE chunks (
    id            VARCHAR(32)  NOT NULL PRIMARY KEY,
    workspace_id  VARCHAR(32)  NOT NULL REFERENCES workspaces (id) ON DELETE CASCADE,
    file_id       VARCHAR(32)  NOT NULL REFERENCES document_files (id) ON DELETE CASCADE,
    parent_id     VARCHAR(32),
    level         VARCHAR(10)  NOT NULL DEFAULT 'child',
    ordinal       INTEGER      NOT NULL DEFAULT 0,
    text          TEXT         NOT NULL,
    location      VARCHAR(300) NOT NULL DEFAULT '',
    meta          TEXT         NOT NULL,
    token_counts  TEXT         NOT NULL,
    token_length  INTEGER      NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL
);

CREATE INDEX ix_chunks_workspace_id ON chunks (workspace_id);
CREATE INDEX ix_chunks_file_id ON chunks (file_id);
CREATE INDEX ix_chunks_parent_id ON chunks (parent_id);
CREATE INDEX ix_chunk_workspace_file ON chunks (workspace_id, file_id);
CREATE INDEX ix_chunk_level_workspace ON chunks (level, workspace_id);

CREATE TABLE messages (
    id           VARCHAR(32) NOT NULL PRIMARY KEY,
    workspace_id VARCHAR(32) NOT NULL REFERENCES workspaces (id) ON DELETE CASCADE,
    -- 提出这条消息的人（assistant 行与系统注入行为 NULL）——多用户下的审计字段。
    user_id      VARCHAR(32) REFERENCES users (id) ON DELETE SET NULL,
    role         VARCHAR(9)  NOT NULL,
    content      TEXT        NOT NULL,
    tool_calls   TEXT,
    citations    TEXT,
    feedback     VARCHAR(10),
    created_at   TIMESTAMPTZ NOT NULL
);

CREATE INDEX ix_messages_workspace_id ON messages (workspace_id);
CREATE INDEX ix_messages_created_at ON messages (created_at);

CREATE TABLE conversation_summaries (
    workspace_id  VARCHAR(32) NOT NULL PRIMARY KEY REFERENCES workspaces (id) ON DELETE CASCADE,
    summary       TEXT        NOT NULL,
    covered_count INTEGER     NOT NULL DEFAULT 0,
    updated_at    TIMESTAMPTZ NOT NULL
);

CREATE TABLE run_traces (
    -- 自增列替代 SQLite 的隐式 rowid：同一毫秒内插入的多个节点靠它保持插入顺序
    -- （trace 详情的对外契约是「按插入顺序返回节点链」）。
    seq         BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id          VARCHAR(32) NOT NULL,
    workspace_id VARCHAR(32) NOT NULL REFERENCES workspaces (id) ON DELETE CASCADE,
    run_id      VARCHAR(32) NOT NULL,
    node        VARCHAR(50) NOT NULL,
    duration_ms INTEGER     NOT NULL DEFAULT 0,
    input       TEXT        NOT NULL,
    output      TEXT        NOT NULL,
    error       TEXT,
    created_at  TIMESTAMPTZ NOT NULL
);

CREATE UNIQUE INDEX uq_run_traces_id ON run_traces (id);
CREATE INDEX ix_run_traces_workspace_id ON run_traces (workspace_id);
CREATE INDEX ix_run_trace_run ON run_traces (workspace_id, run_id);

CREATE TABLE operations (
    id                   VARCHAR(32)  NOT NULL PRIMARY KEY,
    workspace_id         VARCHAR(32)  NOT NULL REFERENCES workspaces (id) ON DELETE CASCADE,
    message_id           VARCHAR(32),
    -- 审批闭环的问责链：谁提的（模型代?用户）、谁批的（多用户下必须能追到人）。
    proposed_by_user_id  VARCHAR(32) REFERENCES users (id) ON DELETE SET NULL,
    resolved_by_user_id  VARCHAR(32) REFERENCES users (id) ON DELETE SET NULL,
    tool_name            VARCHAR(100) NOT NULL,
    rel_path             VARCHAR(500) NOT NULL,
    arguments            TEXT         NOT NULL,
    diff                 TEXT         NOT NULL,
    summary              TEXT         NOT NULL,
    status               VARCHAR(9)   NOT NULL DEFAULT 'proposed',
    backup_path          VARCHAR(1000),
    result               TEXT,
    error                TEXT,
    created_at           TIMESTAMPTZ  NOT NULL,
    resolved_at          TIMESTAMPTZ
);

CREATE INDEX ix_operations_workspace_id ON operations (workspace_id);
CREATE INDEX ix_operations_created_at ON operations (created_at);

-- 工具清单缓存表：当前无读写方（工具清单每次透传 ai-service），保留以维持 schema
-- 形状与文档一致，避免下一轮做工具目录缓存时再补一次迁移。
CREATE TABLE mcp_tools (
    name        VARCHAR(100) NOT NULL PRIMARY KEY,
    description TEXT         NOT NULL,
    read_only   BOOLEAN      NOT NULL DEFAULT FALSE,
    destructive BOOLEAN      NOT NULL DEFAULT FALSE,
    schema_json TEXT         NOT NULL,
    updated_at  TIMESTAMPTZ  NOT NULL
);
